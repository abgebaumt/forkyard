-- Since version 3: begin
-- Account at a host (GitHub, GitLab – self-hosted instances too), accessed through its
-- official API with the user's own token. The token lives in the keychain under
-- "hoster:<id>"; only the details for display are stored here. Replaces the never used table
-- "integrations" of versions 1 and 2.
create table hoster_accounts (
  id             text primary key,
  profile_id     text not null references profiles (id) on delete cascade,
  kind           text not null check (kind in ('github', 'gitlab', 'gitea', 'bitbucket', 'azure_devops')),
  -- Address of the web UI without a trailing slash, e.g. https://github.com
  base_url       text not null,
  -- User name for Basic authentication (Bitbucket); not secret, the token is in the keychain.
  username       text,
  login          text,
  name           text,
  avatar_url     text,
  -- "…" and the last four characters of the token, never more.
  token_hint     text,
  scopes_ok      integer not null default 1 check (scopes_ok in (0, 1)),
  -- Missing permissions of the token, comma-separated.
  missing_scopes text not null default '',
  last_error     text,
  created_at     text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at     text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) strict;
create unique index hoster_accounts_key on hoster_accounts (profile_id, kind, base_url);
-- Since version 3: end

-- Local workspaces: named groups of repositories.
create table workspaces (
  id          text primary key,
  profile_id  text not null references profiles (id) on delete cascade,
  name        text not null,
  description text,
  color       text,
  sync_dir    text,
  created_at  text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at  text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) strict;
create unique index workspaces_name on workspaces (profile_id, name);

create table workspace_repositories (
  workspace_id  text not null references workspaces (id) on delete cascade,
  repository_id text not null references repositories (id) on delete cascade,
  position      integer not null default 0,
  primary key (workspace_id, repository_id)
) strict, without rowid;
create index workspace_repositories_repo on workspace_repositories (repository_id);
