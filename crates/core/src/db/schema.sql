-- Local app database (SQLite). The complete schema in the current version.
-- New databases are created from this file; the core brings existing ones to the same
-- state with the steps in crates/core/src/db/mod.rs (UPGRADES). Whoever adds a column
-- here adds the matching `alter table` there.
--
-- This only holds what the app itself needs to know: profiles, tabs, settings,
-- view state, undo, log. Commits, branches, tags, stashes, remotes, worktrees and
-- submodules are NOT stored here – they are read from Git on every access.
-- Git is the source of truth.
--
-- Conventions:
--   id          text, UUID v4, generated by the app (SQLite has no gen_random_uuid)
--   times       text, UTC, ISO-8601 with Z (SQLite has no timestamptz)
--   updated_at  set by the data layer on every update
--   secrets     (passwords, tokens, passphrases) are never stored in this file but in
--               the operating system's keychain; only the reference is kept here
--   access      single user, no server, no row level security. The data layer
--               filters every query by the active profile.

pragma foreign_keys = on;
pragma journal_mode = wal;

-- Git identity and settings container.
create table profiles (
  id             text primary key,
  name           text not null,
  author_name    text not null,
  author_email   text not null,
  sync_gitconfig integer not null default 0 check (sync_gitconfig in (0, 1)),
  is_active      integer not null default 0 check (is_active in (0, 1)),
  created_at     text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at     text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
-- Since version 5: begin
  -- Lane colour '1' to '8' as in repositories.color; null = by position in the list.
  color          text check (color is null or color in ('1','2','3','4','5','6','7','8')),
-- Since version 5: end
  constraint profile_name_not_empty check (length(trim(name)) > 0)
) strict;
create unique index profiles_name_key on profiles (name);
-- Exactly one active profile.
create unique index profiles_one_active on profiles (is_active) where is_active = 1;

-- Per-profile settings as key/value: the fields of `Settings` (camelCase) that are not
-- global, e.g. autoFetchMinutes, defaultPullMode, proxyUrl. The value is JSON.
create table settings (
  profile_id text not null references profiles (id) on delete cascade,
  key        text not null,
  value      text not null check (json_valid(value)),
  updated_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  primary key (profile_id, key)
) strict, without rowid;

-- Since version 5: begin
-- Global settings (the same for all profiles): appearance, editor, external programs,
-- notifications. Which keys are global is defined by db::app_settings::GLOBAL_KEYS.
create table app_settings (
  key        text primary key,
  value      text not null check (json_valid(value)),
  updated_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) strict, without rowid;
-- Since version 5: end

-- Known repositories, shared by all profiles (path, alias, colour). Which ones a profile
-- lists is stored in profile_repositories.
-- path_key is the normalised path for the uniqueness comparison
-- (lower-cased on Windows and macOS, without a trailing separator).
create table repositories (
  id             text primary key,
  path           text not null,
  path_key       text not null,
  alias          text,
  color          text,
  created_at     text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at     text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) strict;
create unique index repositories_path_key on repositories (path_key);

-- Since version 5: begin
-- Which repositories a profile lists (last opened, favourites, groups).
create table profile_repositories (
  profile_id     text not null references profiles (id) on delete cascade,
  repository_id  text not null references repositories (id) on delete cascade,
  is_favorite    integer not null default 0 check (is_favorite in (0, 1)),
  group_name     text,
  last_opened_at text,
  primary key (profile_id, repository_id)
) strict, without rowid;
create index profile_repositories_recent on profile_repositories (profile_id, last_opened_at desc);
create index profile_repositories_repo on profile_repositories (repository_id);
-- Since version 5: end

-- Since version 4: begin
-- Trust per repository: a row means Git may work in this folder (status, fetch,
-- hooks, …). Without a row the app runs nothing there – a foreign repository can bring
-- commands along in its .git/config. The row is created when the app cloned or created
-- the repository itself, when the check on opening finds nothing suspicious, or when the
-- user agrees.
create table repository_trust (
  repository_id text primary key references repositories (id) on delete cascade,
  trusted_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) strict, without rowid;
-- Since version 4: end

-- Open tabs per profile. A tab shows a repository (optionally a specific
-- worktree of it) or the repository management.
create table tabs (
  id            text primary key,
  profile_id    text not null references profiles (id) on delete cascade,
  kind          text not null check (kind in ('repo', 'repo_management')),
  repository_id text references repositories (id) on delete cascade,
  worktree_path text,
  position      integer not null check (position >= 0),
  is_active     integer not null default 0 check (is_active in (0, 1)),
  created_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  constraint tab_kind_matches_repo check (
    (kind = 'repo' and repository_id is not null) or
    (kind = 'repo_management' and repository_id is null)
  )
) strict;
create index tabs_profile_position on tabs (profile_id, position);
create index tabs_repository on tabs (repository_id);
-- Exactly one active tab per profile.
create unique index tabs_one_active on tabs (profile_id) where is_active = 1;

-- View state per repository: presentation only, changes nothing in the repo.
create table repo_view_state (
  repository_id      text primary key references repositories (id) on delete cascade,
  hidden_refs        text not null default '[]' check (json_valid(hidden_refs)),
  soloed_refs        text not null default '[]' check (json_valid(soloed_refs)),
  pinned_refs        text not null default '[]' check (json_valid(pinned_refs)),
  collapsed_folders  text not null default '[]' check (json_valid(collapsed_folders)),
  columns            text not null default '[]' check (json_valid(columns)),
  section_visibility text not null default '{}' check (json_valid(section_visibility)),
  updated_at         text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
-- Since version 6: begin
  -- Merge commits whose side branch the graph hides (JSON list of SHAs), and "collapse all".
  , collapsed_merges    text not null default '[]' check (json_valid(collapsed_merges))
  , collapse_all_merges integer not null default 0 check (collapse_all_merges in (0, 1))
-- Since version 6: end
) strict;

-- App-side settings per repository (the value is JSON).
-- What Git itself understands (hooksPath, commit.template, signing, LFS)
-- stays in .git/config and is not stored here.
create table repo_settings (
  repository_id text not null references repositories (id) on delete cascade,
  key           text not null,
  value         text not null check (json_valid(value)),
  updated_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  primary key (repository_id, key)
) strict, without rowid;

-- Unfinished commit message per working directory, so it survives tab switches
-- and restarts. worktree_path is '' for the main working directory.
create table commit_drafts (
  repository_id text not null references repositories (id) on delete cascade,
  worktree_path text not null default '',
  summary       text not null default '',
  description   text not null default '',
  is_amend      integer not null default 0 check (is_amend in (0, 1)),
  updated_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  primary key (repository_id, worktree_path)
) strict, without rowid;

-- Results of the statistics (stats_compute) as JSON: derived numbers only, never commits.
-- cache_key names the tip commit, the period and the version of the computation.
create table stats_cache (
  repository_id text not null references repositories (id) on delete cascade,
  cache_key     text not null,
  value         text not null check (json_valid(value)),
  created_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  primary key (repository_id, cache_key)
) strict;

-- Undo/redo. Before every reversible action the app records where HEAD and the
-- affected ref were. For "discard", payload points to a backup commit under
-- refs/<app>/undo/<id>, so that discarded work can be brought back.
create table undo_entries (
  id            text primary key,
  repository_id text not null references repositories (id) on delete cascade,
  worktree_path text not null default '',
  action        text not null check (action in (
                  'checkout', 'commit', 'amend', 'discard', 'delete_branch',
                  'remove_remote', 'reset', 'rebase', 'cherry_pick', 'squash',
                  'reword', 'drop', 'merge', 'revert', 'stash', 'stash_pop')),
  -- Complete sentence for the tooltip of the undo button.
  label         text not null default '',
  ref_name      text,
  ref_before    text,
  ref_after     text,
  head_before   text not null,
  head_after    text,
  payload       text not null default '{}' check (json_valid(payload)),
  state         text not null default 'done' check (state in ('done', 'undone')),
  created_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) strict;
create index undo_entries_repo_time on undo_entries (repository_id, created_at desc);

-- Log of the Git commands and app actions that were run.
-- Credentials are removed from command and output before writing.
create table activity_log (
  id            integer primary key autoincrement,
  scope         text not null check (scope in ('application', 'repository')),
  repository_id text references repositories (id) on delete cascade,
  description   text not null,
  command       text,
  exit_code     integer,
  duration_ms   integer check (duration_ms is null or duration_ms >= 0),
  output        text,
  started_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  -- Error code of a failed call (like ErrorCode in the contract), otherwise null. Since version 2.
  code          text,
  constraint log_scope_matches_repo check (
    (scope = 'repository' and repository_id is not null) or
    (scope = 'application' and repository_id is null)
  )
) strict;
create index activity_log_repo_time on activity_log (repository_id, started_at desc);
create index activity_log_scope_time on activity_log (scope, started_at desc);

-- SSH keys per profile. Paths only; the passphrase lives in the keychain.
create table ssh_keys (
  id               text primary key,
  profile_id       text not null references profiles (id) on delete cascade,
  label            text not null,
  private_key_path text not null,
  public_key_path  text not null,
  is_default       integer not null default 0 check (is_default in (0, 1)),
  created_at       text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at       text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) strict;
create index ssh_keys_profile on ssh_keys (profile_id);
create unique index ssh_keys_one_default on ssh_keys (profile_id) where is_default = 1;

-- Directory of the HTTPS credentials stored in the keychain, so that
-- "Forget all credentials" knows which entries to delete.
create table host_accounts (
  id           text primary key,
  profile_id   text not null references profiles (id) on delete cascade,
  host         text not null,
  username     text not null,
  -- password: HTTPS credentials; passphrase: passphrase of an SSH key.
  kind         text not null default 'password' check (kind in ('password', 'passphrase')),
  keychain_ref text not null,
  created_at   text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at   text not null default (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) strict;
create unique index host_accounts_key on host_accounts (profile_id, host, username);

